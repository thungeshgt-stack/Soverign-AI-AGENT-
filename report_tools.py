"""
DOCX approval-note generation using python-docx.
"""
import os
import time
from docx import Document
from docx.shared import Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH

from config.settings import REPORTS_DIR


def _heading(doc, text, level=1):
    h = doc.add_heading(text, level=level)
    for run in h.runs:
        run.font.color.rgb = RGBColor(0x1E, 0x27, 0x61)
    return h


def create_docx_report(task, reasoning: dict, verification: dict) -> str:
    doc = Document()

    title = doc.add_heading("INDUSTRIAL EQUIPMENT CONDITION ASSESSMENT", level=0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER

    meta = doc.add_paragraph()
    meta.add_run(f"Task ID: {task.task_id}    ").bold = True
    meta.add_run(f"Date: {time.strftime('%Y-%m-%d %H:%M')}    ")
    meta.add_run("AI System: Sovereign AI Workbench").bold = True
    meta.alignment = WD_ALIGN_PARAGRAPH.CENTER

    doc.add_paragraph()

    _heading(doc, "1. Executive Summary")
    doc.add_paragraph(reasoning.get("overall_assessment", "No assessment available."))

    _heading(doc, "2. Equipment Information")
    doc.add_paragraph("Equipment context derived from uploaded inspection documents and sensor data. "
                       "See Section 3 for source documents.")

    _heading(doc, "3. Documents Analyzed")
    docs = task.files.get("pdfs", [])
    if docs:
        for d in docs:
            doc.add_paragraph(os.path.basename(d), style="List Bullet")
    else:
        doc.add_paragraph("No documents were provided for this task.")

    _heading(doc, "4. Sensor Data Findings")
    data_evidence = reasoning.get("data_evidence", [])
    if data_evidence:
        for e in data_evidence:
            doc.add_paragraph(e, style="List Bullet")
    else:
        doc.add_paragraph("No sensor data was provided for this task.")

    _heading(doc, "5. Visual Findings")
    vision_evidence = reasoning.get("vision_evidence", [])
    if vision_evidence:
        for e in vision_evidence:
            doc.add_paragraph(e, style="List Bullet")
    else:
        doc.add_paragraph("No image was provided for this task.")

    _heading(doc, "6. Knowledge Base Evidence")
    kb_evidence = reasoning.get("knowledge_evidence", [])
    if kb_evidence:
        for e in kb_evidence:
            doc.add_paragraph(e, style="List Bullet")
    else:
        doc.add_paragraph("No knowledge base evidence retrieved.")

    _heading(doc, "7. Identified Issues")
    for issue in reasoning.get("possible_issues", ["None identified from available evidence."]):
        doc.add_paragraph(issue, style="List Bullet")

    _heading(doc, "8. Maintenance Recommendation")
    doc.add_paragraph(reasoning.get("recommendation", "No recommendation generated."))

    _heading(doc, "9. Risk Assessment")
    doc.add_paragraph(f"Risk Level: {reasoning.get('risk_level', 'UNKNOWN')}")
    doc.add_paragraph(f"Confidence: {reasoning.get('confidence', 'Evidence-dependent')}")

    _heading(doc, "10. Evidence / Sources")
    for src in reasoning.get("sources", []):
        doc.add_paragraph(src, style="List Bullet")

    _heading(doc, "11. Verification Status")
    doc.add_paragraph(f"Claims supported: {verification.get('supported', 0)}")
    doc.add_paragraph(f"Claims requiring caution: {verification.get('flagged', 0)}")
    doc.add_paragraph(f"Sources available: {verification.get('sources_available', 0)}")
    for note in verification.get("notes", []):
        doc.add_paragraph(note, style="List Bullet")

    _heading(doc, "12. Limitations")
    for lim in reasoning.get("limitations", [
        "This assessment is generated by an AI-assisted workflow and does not replace "
        "certified human inspection.",
    ]):
        doc.add_paragraph(lim, style="List Bullet")

    _heading(doc, "13. Recommended Next Actions")
    for action in reasoning.get("next_actions", ["Schedule human inspection to confirm findings."]):
        doc.add_paragraph(action, style="List Bullet")

    doc.add_paragraph()
    footer = doc.add_paragraph()
    footer.add_run("Generated by Sovereign AI Workbench — AI-assisted draft, requires human review and approval.").italic = True

    out_path = os.path.join(REPORTS_DIR, f"approval_note_{task.task_id}.docx")
    doc.save(out_path)
    return out_path
